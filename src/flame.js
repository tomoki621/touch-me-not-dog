const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);
const ease = (t) => { t = clamp01(t); return t * t * (3 - 2 * t); };
const up = (t, a, b) => ease((t - a) / (b - a));
// 立ち上がって落ちる山。ためと解放のあいだの一瞬だけ効かせたいものに使う。
const pulse = (t, a, b, c) => up(t, a, b) * (1 - up(t, b, c));

// 毎フレーム呼ぶので、入れ物は使い回して新しく作らない。
const W = {
  hold: 0,    // 胸の前で溜める姿勢の重み
  fire: 0,    // 突き出した姿勢の重み
  aim: 0,     // 腕をこちらで作る度合い。0 なら普段の息づかいのまま。
  kick: 0,    // 撃った反動
  gather: 0,  // 集まってくる光
  orb: 0,     // 掌のあいだの玉の明るさ
  orbR: 1,    // 玉の大きさ。放つ直前に縮めて、ためを見せる。
  beam: 0,    // 光線
  muzzle: 0,  // 手元の閃光
  done: false,
};

// 技の始まりからの秒で、その瞬間の姿勢と光の強さを返す。
//
//   0.00–0.90  両手を前へ出して球を抱える形をつくる
//   0.30–2.45  球が生まれて、どんどん大きくなる（ここが「ため」。長く見せる）
//   2.45–2.72  右手を突き出す
//   2.60–3.95  光線
//   3.95–4.60  構えへ戻る
export function flamePose(t){
  // 溜めの姿勢は、突き出しに引き継いで消える。両方を足すのではなく渡す。
  W.hold = up(t, 0.00, 0.90) * (1 - up(t, 2.45, 2.72));
  W.fire = up(t, 2.45, 2.72) * (1 - up(t, 3.95, 4.60));
  // 腕の主導権。技の頭で素早く握り、終わりで手放す。ここが 0 に戻りきらないと
  // 腕が固まったままになる。
  W.aim  = up(t, 0.00, 0.50) * (1 - up(t, 4.05, 4.60));
  W.kick = pulse(t, 2.56, 2.66, 3.25);

  // 光。手が構えるより少し遅れて生まれ、あとはひたすら育つ。縮ませない。
  // 溜めは「大きくなっていく」で見せる。縮めると、そこで一度終わって見える。
  const g = up(t, 0.30, 1.10) * (1 - up(t, 2.50, 2.64));
  W.gather = g;
  W.orb = g * (0.45 + 0.55 * up(t, 0.90, 2.45));
  W.orbR = 0.30 + 0.70 * up(t, 0.35, 2.45);
  W.beam = up(t, FLAME_SHOT, 2.72) * (1 - up(t, 3.60, 3.95));
  W.muzzle = Math.max(W.beam * 0.55, pulse(t, 2.56, 2.66, 3.05));

  W.done = t >= FLAME_END;
  return W;
}

// 体幹の角度をひとつ取り出す。表の並びを読む側それぞれで書くと、係数の順番を
// 取り違えたときに片方だけずれる。
export function trunkAngle(coef, w){
  return coef[3] * w.hold + coef[4] * w.fire + coef[5] * w.kick;
}
